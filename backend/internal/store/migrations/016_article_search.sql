-- Article search (PERF-3) uses pg_trgm.
--
-- pg_trgm is a trusted extension (PostgreSQL 13+): a database owner without superuser
-- rights may create it. It is installed in the public schema so that it survives
-- independently of any per-session search_path.
--
-- The first version of this file also added articles.search_text, filled it for every
-- row, and built a trigram index on it inside the startup transaction, which took
-- minutes on large databases. The search column is now added by
-- 018_article_search_key.sql without rewriting rows, and filled and indexed after start
-- by store.ArticleSearchUpgrade; 018 also removes what the first version created.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
